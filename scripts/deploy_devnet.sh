#!/bin/bash
# ============================================================================
# Brother ID — local starknet-devnet deployment
# ============================================================================
#
# Deploys BrotherNamingService and IdentityContract to a local devnet started with:
#   starknet-devnet --seed 42 --chain-id TESTNET
# The devnet predeploys STRK at the same address as Sepolia, so the frontend's
# STRK constant works unchanged. Outputs client1/.env.local for `npm run dev`.
#
# Usage: ./scripts/deploy_devnet.sh
# ============================================================================

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RPC_URL="${DEVNET_RPC_URL:-http://127.0.0.1:5050/rpc}"
STATE_DIR="${ROOT}/.local-devnet"
ACCOUNTS_FILE="${STATE_DIR}/accounts.json"
ACCOUNT_NAME="devnet0"
STRK_TOKEN_ADDRESS="0x04718f5a0fc34cc1af16a1cdee98ffb20c31f5cd61d6ab07201858f4287c938d"

mkdir -p "$STATE_DIR"

# First predeployed account of `starknet-devnet --seed 42`. Local test key only.
ACCOUNT_JSON="$(curl -sf -X POST "${RPC_URL%/rpc}/rpc" -H 'content-type: application/json' \
  -d '{"jsonrpc":"2.0","id":1,"method":"devnet_getPredeployedAccounts"}')"
OWNER_ADDRESS="$(echo "$ACCOUNT_JSON" | python3 -c 'import json,sys; print(json.load(sys.stdin)["result"][0]["address"])')"
OWNER_KEY="$(echo "$ACCOUNT_JSON" | python3 -c 'import json,sys; print(json.load(sys.stdin)["result"][0]["private_key"])')"

echo "🔷 Brother ID — devnet deployment"
echo "   RPC   : ${RPC_URL}"
echo "   Owner : ${OWNER_ADDRESS}"

rm -f "$ACCOUNTS_FILE"
sncast --accounts-file "$ACCOUNTS_FILE" account import --url "$RPC_URL" \
  --name "$ACCOUNT_NAME" --address "$OWNER_ADDRESS" --private-key "$OWNER_KEY" --type oz --silent >/dev/null

cd "${ROOT}/contracts/brotherdomain"
CAST=(sncast --accounts-file "$ACCOUNTS_FILE" --account "$ACCOUNT_NAME" --json)

declare_class() {
  "${CAST[@]}" declare --url "$RPC_URL" --contract-name "$1" \
    | python3 -c 'import json,sys
for line in sys.stdin:
    line=line.strip()
    if not line.startswith("{"): continue
    d=json.loads(line)
    if "class_hash" in d: print(d["class_hash"]); break'
}

deploy_class() {
  local class_hash="$1"; shift
  "${CAST[@]}" deploy --url "$RPC_URL" --class-hash "$class_hash" --constructor-calldata "$@" \
    | python3 -c 'import json,sys
for line in sys.stdin:
    line=line.strip()
    if not line.startswith("{"): continue
    d=json.loads(line)
    if "contract_address" in d: print(d["contract_address"]); break'
}

echo "📦 Declaring BrotherNamingService..."
BNS_CLASS="$(declare_class BrotherNamingService)"
echo "📦 Declaring IdentityContract..."
IDENTITY_CLASS="$(declare_class IdentityContract)"

echo "🚀 Deploying BrotherNamingService (owner, STRK, treasury=owner)..."
BNS_ADDRESS="$(deploy_class "$BNS_CLASS" "$OWNER_ADDRESS" "$STRK_TOKEN_ADDRESS" "$OWNER_ADDRESS")"
echo "🚀 Deploying IdentityContract (owner, STRK)..."
IDENTITY_ADDRESS="$(deploy_class "$IDENTITY_CLASS" "$OWNER_ADDRESS" "$STRK_TOKEN_ADDRESS")"

cat > "${STATE_DIR}/deployment.json" <<EOF
{
  "rpc": "${RPC_URL}",
  "owner": "${OWNER_ADDRESS}",
  "strk": "${STRK_TOKEN_ADDRESS}",
  "bns": { "class_hash": "${BNS_CLASS}", "address": "${BNS_ADDRESS}" },
  "identity": { "class_hash": "${IDENTITY_CLASS}", "address": "${IDENTITY_ADDRESS}" }
}
EOF

cat > "${ROOT}/client1/.env.local" <<EOF
# Generated by scripts/deploy_devnet.sh — points the app at the local devnet.
VITE_STARKNET_SEPOLIA_RPC=${RPC_URL}
VITE_BNS_CONTRACT_ADDRESS=${BNS_ADDRESS}
VITE_IDENTITY_CONTRACT_ADDRESS=${IDENTITY_ADDRESS}
EOF

echo ""
echo "✅ BrotherNamingService : ${BNS_ADDRESS}"
echo "✅ IdentityContract     : ${IDENTITY_ADDRESS}"
echo "   Wrote .local-devnet/deployment.json and client1/.env.local"
